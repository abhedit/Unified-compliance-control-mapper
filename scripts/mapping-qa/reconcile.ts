// Mapping QA: reconcile the Unified Control Library against an independent reference
// crosswalk (the Secure Controls Framework) and regenerate provenance + the QA report.
//
//   python3 scripts/mapping-qa/extract_scf.py <scf.xlsx> scf-reference.json
//   node --experimental-strip-types scripts/mapping-qa/reconcile.ts scf-reference.json [--detail]
//
// Outputs:
//   src/data/provenance.ts        set of library links corroborated by the reference
//   docs/mapping-qa-report.md     corroboration, STRM distribution and coverage metrics
import { readFileSync, writeFileSync } from "node:fs";
import { CONTROLS, LIBRARY_VERSION } from "../../src/data/controls.ts";
import { FRAMEWORKS } from "../../src/data/frameworks.ts";
import { REL_META, buildIndex, key, relationship, type Relationship } from "../../src/lib/mapper.ts";

const [refPath, flag] = process.argv.slice(2);
if (!refPath) throw new Error("usage: reconcile.ts <scf-reference.json> [--detail]");
const ref = JSON.parse(readFileSync(refPath, "utf8")) as {
  version: string;
  controls: { id: string; refs: Record<string, string[]> }[];
  universe: Record<string, string[]>;
};
const hasReference = (fw: string) => (ref.universe[fw]?.length ?? 0) > 0;
const scf = new Map(ref.controls.map((c) => [c.id, c]));
const catalog = Object.fromEntries(FRAMEWORKS.map((f) => [f.id, new Set(f.requirements.map((r) => r.code))]));

/** Roll a reference code up to catalog granularity (e.g. HIPAA sub-paragraphs). */
// ISO management-system catalogs list one representative entry per sub-clause family
// (e.g. 9.3.1 stands for 9.3.x), so reference sub-clauses roll up to their sibling.
const SIBLING_ROLLUP = new Set(["iso42001", "iso22301"]);
export function roll(fw: string, code: string): string | null {
  if (catalog[fw].has(code)) return code;
  let best: string | null = null;
  for (const c of catalog[fw]) if ((code.startsWith(c + "(") || code.startsWith(c + ".")) && (!best || c.length > best.length)) best = c;
  if (best || !SIBLING_ROLLUP.has(fw)) return best;
  for (let parts = code.split("."); parts.length > 1; parts = parts.slice(0, -1)) {
    const parent = parts.slice(0, -1).join(".");
    const sib = [...catalog[fw]].find((c) => c.startsWith(parent + ".") && c.split(".").length === parts.length);
    if (sib) return sib;
  }
  return null;
}

const missingAnchors = CONTROLS.flatMap((c) => c.scf.filter((a) => !scf.has(a)).map((a) => `${c.id} -> ${a}`));
if (missingAnchors.length) throw new Error(`Unknown SCF anchors: ${missingAnchors.join(", ")}`);

const corroborated: string[] = [];
const stats: Record<string, { links: number; corroborated: number; suggestions: number }> = {};
const detail: string[] = [];
for (const f of FRAMEWORKS) stats[f.id] = { links: 0, corroborated: 0, suggestions: 0 };

for (const c of CONTROLS) {
  for (const f of FRAMEWORKS) {
    const ours = c.map[f.id] ?? [];
    const implied = new Set<string>();
    for (const a of c.scf) for (const code of scf.get(a)!.refs[f.id] ?? []) {
      const r = roll(f.id, code);
      if (r) implied.add(r);
    }
    const hits = ours.filter((x) => implied.has(x));
    const extra = [...implied].filter((x) => !ours.includes(x));
    stats[f.id].links += ours.length;
    stats[f.id].corroborated += hits.length;
    stats[f.id].suggestions += extra.length;
    hits.forEach((x) => corroborated.push(`${c.id}|${f.id}|${x}`));
    const own = ours.filter((x) => !implied.has(x));
    if (flag === "--detail" && (own.length || extra.length)) detail.push(`${c.id} ${f.id}: analyst-only [${own.join(" ")}]  reference-only [${extra.join(" ")}]`);
  }
}

// STRM distribution + coverage completeness
const relCount: Record<Relationship, number> = { equal: 0, subset_of: 0, superset_of: 0, intersects_with: 0 };
const index = buildIndex(CONTROLS);
const coverageRows = FRAMEWORKS.map((f) => {
  let full = 0, composite = 0, supportiveOnly = 0;
  for (const r of f.requirements) {
    const linked = index.get(key(f.id, r.code)) ?? [];
    const rels = linked.map((c) => relationship(c, f.id, r.code));
    rels.forEach((x) => relCount[x]++);
    if (rels.some((x) => REL_META[x].full)) full++;
    else if (rels.some((x) => x === "superset_of")) composite++;
    else supportiveOnly++;
  }
  return { f, full, composite, supportiveOnly };
});

const generatedAt = new Date().toISOString().slice(0, 10);
writeFileSync(
  new URL("../../src/data/provenance.ts", import.meta.url),
  `// Generated by scripts/mapping-qa/reconcile.ts — do not edit by hand.\n` +
    `// Library links independently corroborated by the ${ref.version} crosswalk (via each control's SCF anchors).\n` +
    `export const REFERENCE = { name: "Secure Controls Framework (SCF)", version: ${JSON.stringify(ref.version)}, generatedAt: ${JSON.stringify(generatedAt)} };\n` +
    `export const CORROBORATED: ReadonlySet<string> = new Set<string>(${JSON.stringify(corroborated.sort(), null, 0).replace(/","/g, '",\n  "').replace(/^\[/, "[\n  ").replace(/\]$/, ",\n]")});\n`,
);

const totLinks = Object.values(stats).reduce((n, s) => n + s.links, 0);
const totCorr = Object.values(stats).reduce((n, s) => n + s.corroborated, 0);
const pct = (a: number, b: number) => (b ? `${Math.round((100 * a) / b)}%` : "—");
const md = [
  `# Mapping QA report`,
  ``,
  `Generated ${generatedAt} for Unified Control Library **v${LIBRARY_VERSION}** (${CONTROLS.length} controls, ${totLinks} mapping links) against **${ref.version}**.`,
  `See [MAPPING_METHODOLOGY.md](../MAPPING_METHODOLOGY.md) for the procedure.`,
  ``,
  `## 1. Independent corroboration`,
  ``,
  `A link is *corroborated* when the reference crosswalk, reached through the control's SCF anchor controls, maps the same requirement.`,
  `Links not corroborated are analyst-asserted and were individually reviewed (see methodology §5).`,
  `Frameworks the reference does not cover at catalog granularity (e.g. UK Cyber Essentials themes, CCPA statute sections, CERT-In Directions) are fully analyst-mapped.`,
  ``,
  `| Framework | Links | Corroborated | Rate | Reference suggestions reviewed |`,
  `|---|---:|---:|---:|---:|`,
  ...FRAMEWORKS.map((f) =>
    hasReference(f.id)
      ? `| ${f.name} | ${stats[f.id].links} | ${stats[f.id].corroborated} | ${pct(stats[f.id].corroborated, stats[f.id].links)} | ${stats[f.id].suggestions} |`
      : `| ${f.name} | ${stats[f.id].links} | — | n/a — no reference crosswalk; analyst-mapped | — |`,
  ),
  `| **Total** | **${totLinks}** | **${totCorr}** | **${pct(totCorr, totLinks)}** | |`,
  ``,
  `Reference suggestions that remain open were reviewed and rejected as over-mapping: typically program-level reference controls`,
  `(e.g. "governance policy") that the reference links to every standard of a framework, where the library assigns a more specific control.`,
  ``,
  `## 2. Relationship types (NIST IR 8477 STRM)`,
  ``,
  `| Relationship | Meaning | Links |`,
  `|---|---|---:|`,
  ...(Object.keys(relCount) as Relationship[]).map((r) => `| ${REL_META[r].symbol} ${REL_META[r].label} | ${REL_META[r].help} | ${relCount[r]} |`),
  ``,
  `## 3. Coverage completeness`,
  ``,
  `Every catalogued requirement must be addressable by the library: either by a fully-covering control (=, ⊂) or by a composite of partial controls (⊃).`,
  ``,
  `| Framework | Requirements | Full | Composite | Supportive only |`,
  `|---|---:|---:|---:|---:|`,
  ...coverageRows.map((r) => `| ${r.f.name} | ${r.f.requirements.length} | ${r.full} | ${r.composite} | ${r.supportiveOnly} |`),
  ``,
].join("\n");
writeFileSync(new URL("../../docs/mapping-qa-report.md", import.meta.url), md);

console.log(`${totCorr}/${totLinks} links corroborated (${pct(totCorr, totLinks)}); provenance and QA report written.`);
if (detail.length) console.log(detail.join("\n"));
